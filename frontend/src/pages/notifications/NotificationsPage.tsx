import { Bell, BellOff, Check, CheckCheck } from 'lucide-react';
import { useCallback, useEffect, useState } from 'react';
import { Link } from 'react-router-dom';

import {
  listNotifications,
  markAllNotificationsRead,
  markNotificationRead,
  muteNotification,
  type NotificationRecord,
  unmuteNotification
} from '../../api/notifications';
import { EmptyState } from '../../components/shared/EmptyState';
import { StatusBadge } from '../../components/shared/StatusBadge';

const workflowPaths = new Set([
  '/approvals',
  '/reports/daily',
  '/documents',
  '/finance',
  '/materials'
]);

function workflowLink(body: string) {
  // Workflow notifications end with the link generated by append_link on the API.
  const match = /\n\n(Open [a-z ]+): (https?:\/\/\S+)$/.exec(body);
  if (!match) return null;
  try {
    const url = new URL(match[2]);
    if (
      url.origin !== window.location.origin ||
      url.username ||
      url.password ||
      !workflowPaths.has(url.pathname)
    ) {
      return null;
    }
    return { message: body.slice(0, match.index), label: match[1], to: url.pathname + url.search };
  } catch {
    return null;
  }
}

export function NotificationsPage() {
  const [notifications, setNotifications] = useState<NotificationRecord[]>([]);
  const [error, setError] = useState<string | null>(null);

  const loadNotifications = useCallback(async () => {
    try {
      const response = await listNotifications();
      setNotifications(response.items);
    } catch {
      setError('Unable to load notifications.');
    }
  }, []);

  useEffect(() => {
    void loadNotifications();
  }, [loadNotifications]);

  async function markAllRead() {
    await markAllNotificationsRead();
    await loadNotifications();
  }

  async function markRead(notification: NotificationRecord) {
    if (notification.is_read) return;
    await markNotificationRead(notification.id);
    await loadNotifications();
  }

  async function toggleMute(notification: NotificationRecord) {
    if (notification.muted) {
      await unmuteNotification(notification.id);
    } else {
      await muteNotification(notification.id);
    }
    await loadNotifications();
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col justify-between gap-3 sm:flex-row sm:items-end">
        <div>
          <p className="text-sm font-medium text-brand-600">Notifications</p>
          <h2 className="text-2xl font-semibold text-theme-text-primary">Notification History</h2>
        </div>
        <button
          className="inline-flex min-h-10 items-center justify-center gap-2 rounded-md border border-theme-border px-3 py-2 text-sm font-semibold text-theme-text-secondary hover:bg-theme-card-elevated"
          onClick={() => void markAllRead()}
          type="button"
        >
          <CheckCheck className="h-4 w-4" />
          Mark all read
        </button>
      </div>

      {error ? <p className="alert-error rounded-md px-3 py-2 text-sm">{error}</p> : null}

      {notifications.length === 0 ? (
        <EmptyState
          description="Workflow alerts, approvals, and reminders will appear here."
          title="No notifications"
        />
      ) : (
        <div className="space-y-3">
          {notifications.map((notification) => {
            const link = workflowLink(notification.body);
            return (
              <article
                className="w-full rounded-lg border border-theme-border bg-theme-card p-4 text-left shadow-xs hover:bg-theme-card-elevated"
                key={notification.id}
              >
                <div className="flex items-start justify-between gap-3">
                  <div className="min-w-0">
                    <p className="text-sm font-semibold text-theme-text-primary">
                      {notification.title}
                    </p>
                    <p className="mt-1 whitespace-pre-line break-words text-sm text-theme-text-secondary">
                      {link?.message ?? notification.body}
                    </p>
                    {link && (
                      <Link
                        className="mt-2 inline-block text-sm font-semibold text-brand-600 underline"
                        to={link.to}
                      >
                        {link.label}
                      </Link>
                    )}
                    <p className="mt-2 text-xs text-theme-text-muted">
                      {new Date(notification.created_at).toLocaleString()}
                    </p>
                  </div>
                  <div className="flex shrink-0 items-center gap-2">
                    <StatusBadge
                      tone={
                        notification.muted ? 'warning' : notification.is_read ? 'neutral' : 'info'
                      }
                    >
                      {notification.muted ? 'muted' : notification.is_read ? 'read' : 'unread'}
                    </StatusBadge>
                    {!notification.is_read ? (
                      <button
                        aria-label="Mark notification read"
                        className="inline-flex h-9 w-9 items-center justify-center rounded-md border border-theme-border text-theme-text-secondary hover:bg-theme-card-elevated"
                        onClick={() => void markRead(notification)}
                        type="button"
                      >
                        <Check className="h-4 w-4" />
                      </button>
                    ) : null}
                    <button
                      aria-label={notification.muted ? 'Unmute notification' : 'Mute notification'}
                      className="inline-flex h-9 w-9 items-center justify-center rounded-md border border-theme-border text-theme-text-secondary hover:bg-theme-card-elevated"
                      onClick={() => void toggleMute(notification)}
                      type="button"
                    >
                      {notification.muted ? (
                        <Bell className="h-4 w-4" />
                      ) : (
                        <BellOff className="h-4 w-4" />
                      )}
                    </button>
                  </div>
                </div>
              </article>
            );
          })}
        </div>
      )}
    </div>
  );
}
